function animFrame(anim, t) {
  const a = ANIMS[anim];
  let total = 0;
  for (const s of a.seq) total += s[1];
  let tt = a.loop ? t % total : Math.min(t, total - 1);
  for (const s of a.seq) {
    if (tt < s[1]) return s[0];
    tt -= s[1];
  }
  return a.seq[a.seq.length - 1][0];
}

// 스프라이트 그리기: 좌우·상하 뒤집기, 찌그러짐(스쿼시), 팔레트 변형
function drawSprite(ctx, sheet, key, x, y, o = {}) {
  const c = sheet.canvas(key, o.variant || 'base');
  const sx = (o.sx || 1) * (o.flipX ? -1 : 1);
  const sy = (o.sy || 1) * (o.flipY ? -1 : 1);
  if (sx === 1 && sy === 1 && !o.alpha) {
    ctx.drawImage(c, Math.round(x), Math.round(y));
    return;
  }
  ctx.save();
  if (o.alpha != null) ctx.globalAlpha = o.alpha;
  const cxp = Math.round(x) + 8, cyp = Math.round(y) + (o.flipY ? 8 : 16);
  ctx.translate(cxp, cyp);
  ctx.scale(sx, sy);
  ctx.drawImage(c, -8, o.flipY ? -8 : -16);
  ctx.restore();
}
