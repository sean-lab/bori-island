// 포도: 5×5 공 모양 도장을 여섯 번 찍어서 만든다
(function buildGrape() {
  const g = Array.from({ length: 16 }, () => Array(16).fill('.'));
  const ball = ['.111.', '12dd1', '1ddd1', '1ddd1', '.111.'];
  const stamp = (x, y) => ball.forEach((row, j) => [...row].forEach((c, i) => { if (c !== '.') g[y + j][x + i] = c; }));
  [[2, 3], [6, 3], [10, 3], [4, 6], [8, 6], [6, 9]].forEach(([x, y]) => stamp(x, y));
  g[0][8] = '5'; g[1][8] = '5'; g[2][8] = '5'; g[3][8] = '1';
  g[1][9] = '8'; g[1][10] = '8'; g[0][10] = '8'; g[2][9] = '9';
  SPRITE_SRC.item.frames.grape = g.map((r) => r.join(''));
})();

const HEX_CHARS = '.123456789abcdef';
function decodeRows(rows) {
  const out = new Uint8Array(16 * 16);
  rows.forEach((row, y) => {
    for (let x = 0; x < 16; x++) out[y * 16 + x] = Math.max(0, HEX_CHARS.indexOf(row[x] || '.'));
  });
  return out;
}
function encodeRows(data) {
  const rows = [];
  for (let y = 0; y < 16; y++) {
    let s = '';
    for (let x = 0; x < 16; x++) s += HEX_CHARS[data[y * 16 + x]];
    rows.push(s);
  }
  return rows;
}

// 시트: 같은 크기의 프레임 묶음 + 팔레트. 캔버스는 필요할 때 만들어 캐시한다.
class Sheet {
  constructor(name, src, palette) {
    this.name = name;
    this.label = src.label;
    this.w = 16; this.h = 16;
    this.keys = Object.keys(src.frames);
    this.defaults = this.keys.map((k) => decodeRows(src.frames[k]));
    this.data = this.defaults.map((d) => new Uint8Array(d));
    this.palette = palette;
    this.version = 0;
    this.cache = new Map();
  }
  index(key) { return this.keys.indexOf(key); }
  canvas(key, variant = 'base') {
    const i = typeof key === 'number' ? key : this.index(key);
    const ck = i + ':' + variant;
    let c = this.cache.get(ck);
    if (c) return c;
    c = document.createElement('canvas');
    c.width = this.w; c.height = this.h;
    const cx = c.getContext('2d');
    const img = cx.createImageData(this.w, this.h);
    const pal = paletteFor(this.palette, variant).map((h) => (h ? hexToRgb(h) : null));
    const d = this.data[i];
    for (let p = 0; p < d.length; p++) {
      const col = pal[d[p]];
      if (!col) continue;
      img.data[p * 4] = col[0]; img.data[p * 4 + 1] = col[1]; img.data[p * 4 + 2] = col[2]; img.data[p * 4 + 3] = 255;
    }
    cx.putImageData(img, 0, 0);
    this.cache.set(ck, c);
    return c;
  }
  touch() {
    this.version++;
    this.cache.clear();
    Bus.emit('sheet', this);
  }
  isModified(i) {
    const a = this.data[i], b = this.defaults[i];
    for (let p = 0; p < a.length; p++) if (a[p] !== b[p]) return true;
    return false;
  }
  serialize() {
    const out = {};
    this.keys.forEach((k, i) => { if (this.isModified(i)) out[k] = encodeRows(this.data[i]).join(''); });
    return out;
  }
  restore(obj) {
    if (!obj) return;
    this.keys.forEach((k, i) => {
      const s = obj[k];
      if (typeof s === 'string' && s.length === 256) {
        const rows = [];
        for (let y = 0; y < 16; y++) rows.push(s.slice(y * 16, y * 16 + 16));
        this.data[i] = decodeRows(rows);
      }
    });
    this.version++; this.cache.clear();
  }
}

