const FONT_CHARS = Object.keys(FONT_SRC);
const FONT = { w: 5, h: 7, adv: 6, line: 9, atlas: new Map() };

function fontAtlas(color) {
  let a = FONT.atlas.get(color);
  if (a) return a;
  a = document.createElement('canvas');
  a.width = FONT_CHARS.length * FONT.adv; a.height = FONT.h;
  const cx = a.getContext('2d');
  cx.fillStyle = color;
  FONT_CHARS.forEach((ch, i) => {
    FONT_SRC[ch].forEach((row, y) => {
      for (let x = 0; x < 5; x++) if (row[x] === '#') cx.fillRect(i * FONT.adv + x, y, 1, 1);
    });
  });
  FONT.atlas.set(color, a);
  return a;
}

function textWidth(str, scale = 1) { return str.length * FONT.adv * scale - scale; }

// 글자마다 아틀라스에서 잘라 그린다. shadow는 1픽셀 아래·오른쪽 그림자.
function drawText(ctx, str, x, y, o = {}) {
  const scale = o.scale || 1;
  const s = String(str).toUpperCase().replace(/×/g, 'x');
  let cx = Math.round(x);
  if (o.align === 'center') cx = Math.round(x - textWidth(s, scale) / 2);
  else if (o.align === 'right') cx = Math.round(x - textWidth(s, scale));
  const draw = (color, dx, dy) => {
    const atlas = fontAtlas(color);
    let px = cx + dx;
    for (const ch of s) {
      const i = FONT_CHARS.indexOf(ch === 'X' && o.times ? 'x' : ch);
      if (i >= 0) ctx.drawImage(atlas, i * FONT.adv, 0, 5, 7, px, Math.round(y) + dy, 5 * scale, 7 * scale);
      px += FONT.adv * scale;
    }
  };
  if (o.shadow !== false) draw(o.shadowColor || '#000000', scale, scale);
  draw(o.color || '#FFFFFF', 0, 0);
}
